if set(_EN) != set(_BG):
    raise RuntimeError("profile localization catalogues must have identical keys")

_CATALOGUES = MappingProxyType(
    {
        ProfileLocale.ENGLISH: MappingProxyType(_EN),
        ProfileLocale.BULGARIAN: MappingProxyType(_BG),
    }
)
PROFILE_MESSAGE_KEYS = frozenset(_EN)
_FORMAT_FIELDS = MappingProxyType(
    {
        key: frozenset(
            field_name
            for _literal, field_name, _format_spec, _conversion in string.Formatter().parse(value)
            if field_name is not None
        )
        for key, value in _EN.items()
    }
)


def normalize_locale(value: Any, *, allow_pseudo: bool = False) -> ProfileLocale:
    try:
        locale = value if isinstance(value, ProfileLocale) else ProfileLocale(value)
    except (TypeError, ValueError) as exc:
        raise ProfileLocalizationError("unsupported profile locale") from exc
    if locale is ProfileLocale.PSEUDO and not allow_pseudo:
        raise ProfileLocalizationError("pseudo locale is test-only")
    return locale


def profile_text(locale: Any, key: str, **values: str) -> str:
    exact_locale = normalize_locale(locale, allow_pseudo=True)
    if type(key) is not str or key not in PROFILE_MESSAGE_KEYS:
        raise ProfileLocalizationError("unsupported profile message identifier")
    base_locale = (
        ProfileLocale.ENGLISH
        if exact_locale is ProfileLocale.PSEUDO
        else exact_locale
    )
    if set(values) != _FORMAT_FIELDS[key] or any(type(value) is not str for value in values.values()):
        raise ProfileLocalizationError("invalid profile message values")
    try:
        rendered = _CATALOGUES[base_locale][key].format(**values)
    except (KeyError, ValueError) as exc:
        raise ProfileLocalizationError("invalid profile message values") from exc
    if exact_locale is ProfileLocale.PSEUDO:
        return f"⟦ {rendered} ··· {rendered[: max(1, len(rendered) // 3)]} ⟧"
    return rendered


